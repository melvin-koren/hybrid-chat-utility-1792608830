#!/bin/bash
set -e
echo "[+] 3/3 Запуск сквозной консольной автоматизации через GitHub CLI..."

GH_BIN="/usr/bin/gh"

# 1. Принудительный сброс путей и удаление старых битых ссылок
sudo rm -f /usr/local/bin/gh
hash -r

# 2. Интерактивная консольная авторизация стандартным надежным методом
if ! $GH_BIN auth status &>/dev/null; then
    echo "========================================================================"
    echo "🔑 КОНСОЛЬНАЯ АВТОРИЗАЦИЯ GITHUB"
    echo "========================================================================"
    echo "👉 Сейчас утилита сгенерирует код авторизации."
    echo "👉 Когда появится строка 'Press Enter to open github.com...', просто нажмите ENTER."
    echo "👉 Если браузер не откроется сам, скопируйте код и введите его вручную."
    echo "------------------------------------------------------------------------"
    sleep 2
    # Запускаем официальный интерактивный вход
    $GH_BIN auth login --git-protocol https --web
fi

# 3. Инициализация локального Git репозитория
REPO_NAME="covert-messenger-$(date +%s)"
if [ ! -d ".git" ]; then
    git init -b main
fi
git add .
git commit -m "Automated stable GHA multiplatform build" --quiet || echo "Изменения уже закоммичены"

# 4. Создание закрытого репозитория и пуш кода в облако GitHub
echo "[+] Создание закрытого репозитория $REPO_NAME на вашем GitHub..."
$GH_BIN repo create "$REPO_NAME" --private --source=. --remote=origin --push

echo "=============================================================================="
echo "🚀 Код успешно загружен в облако!"
echo "Подключение к интерактивному прогресс-бару компиляции..."
echo "=============================================================================="
sleep 2

# 5. Запуск живого вывода прогресса выполнения шагов сборки в консоль
$GH_BIN run watch
